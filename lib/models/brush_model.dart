  bool isPressureSensitive;
  double hardness; // 0.0=suave, 1.0=duro

  BrushModel({
    required this.id,
    required this.name,
    required this.emoji,
    required this.type,
    required this.category,
    this.size = 5.0,
    this.opacity = 1.0,
    this.spacing = 1.0,
    this.isPressureSensitive = true,
    this.hardness = 1.0,
  });

  BrushModel copyWith({
    String? id,
    String? name,
    String? emoji,
    StrokeType? type,
    BrushCategory? category,
    double? size,
    double? opacity,
    double? spacing,
    bool? isPressureSensitive,
    double? hardness,
  }) {
    return BrushModel(
      id: id ?? this.id,
      name: name ?? this.name,
      emoji: emoji ?? this.emoji,
      type: type ?? this.type,
      category: category ?? this.category,
      size: size ?? this.size,
      opacity: opacity ?? this.opacity,
      spacing: spacing ?? this.spacing,
      isPressureSensitive: isPressureSensitive ?? this.isPressureSensitive,
      hardness: hardness ?? this.hardness,
    );
  }

