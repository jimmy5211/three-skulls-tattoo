  // Filtrar por categoría
  static List<BrushModel> byCategory(
      List<BrushModel> brushes, BrushCategory category) {
    if (category == BrushCategory.todos) return brushes;
    return brushes
        .where((b) => b.category == category)
        .toList();
  }

